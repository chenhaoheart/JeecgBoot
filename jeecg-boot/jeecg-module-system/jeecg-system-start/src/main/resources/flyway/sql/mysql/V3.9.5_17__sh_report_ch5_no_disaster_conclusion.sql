--
-- 背景：历史山洪灾害并非每个流域都会发生，上游查不到灾害记录属于「该流域本次调查未发现」，
-- 是有效的调查结论，而不是数据缺失。原提示词写的是「若资料为空，则撰写章节框架并说明需补充
-- 历史灾害调查资料」，模型据此输出「| 待补充 | — | — |」空占位表 + 「后续应补充」，被质检判为
-- 占位符残留（BLOCK）→ 反复重写同一份内容直到耗尽 maxRetry → 第五章整章失败。
--
-- 1) 通用约束（所有章节）：统计数据为空时写明调查结论，禁止空占位表与未完成标记
UPDATE `airag_flow`
SET `design` = REPLACE(`design`,
    '报告针对单一小流域编写，行文中始终使用给定的流域名称。',
    '报告针对单一小流域编写，行文中始终使用给定的流域名称。'
    '若某项统计数据为空，只说明该指标在本流域客观不存在或本次调查未发现，'
    '应直接写明「本次调查未发现」或「该指标暂无数据」这一调查结论，'
    '严禁输出空占位表格，严禁出现 XX、TBD、待补充、待填写、（待补充）等未完成标记。'),
    `update_time` = NOW()
WHERE `name` LIKE '山洪报告_%'
  AND `design` LIKE '%报告针对单一小流域编写，行文中始终使用给定的流域名称。%'
  AND `design` NOT LIKE '%若某项统计数据为空%';

